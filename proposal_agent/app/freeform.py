def _versions_of(data: dict[str, Any]) -> list[dict[str, Any]]:
    versions = data.get("freeform_versions")
    return [v for v in versions if isinstance(v, dict)] if isinstance(versions, list) else []


def next_version_number(data: dict[str, Any]) -> int:
    return max([int(v.get("version") or 0) for v in _versions_of(data)] + [0]) + 1


def publish_outcome(run: Run, store: Store, data: dict[str, Any], outcome: Outcome) -> dict[str, Any]:
    """Copies the chosen build to presentations/<id>/v<N>/ and returns the Firestore updates (not applied)."""
    assert outcome.chosen is not None
    run.status("freeform_publishing", "公開しています")
    version = next_version_number(data)
    prefix = f"presentations/{run.presentation_id}/v{version}/"
    chosen = outcome.chosen
    store.write_many(prefix, chosen.build.files)
    qa_files: dict[str, bytes] = {}
    for slide in (chosen.render or {}).get("slides", []):
        if slide.get("screenshot_b64"):
            qa_files[f"_qa/slide_{int(slide.get('index', 0)) + 1:02d}.jpg"] = base64.b64decode(slide["screenshot_b64"])
    if qa_files:
        store.write_many(prefix, qa_files)
    now = _now_iso()
    titles = [s.title for s in chosen.build.slides]
    versions = _versions_of(data)
    previous_mode = str(data.get("render_mode") or "")
    previous_meta = data.get("freeform") if isinstance(data.get("freeform"), dict) else {}
    versions.append(
        {
            "version": version,
            "render_mode": "freeform",
            "prefix": prefix,
            "created_at": now,
            "turn_id": outcome.turn_ids[0] if outcome.turn_ids else "",
            "slide_count": chosen.build.slide_count,
            "slide_titles": titles[:40],
            # Undo returns to the version this one was edited from (0 = created or converted from the template).
            "based_on": int(previous_meta.get("current_version") or 0) if previous_mode == "freeform" else 0,
            "based_on_render_mode": previous_mode,
        }
    )
    freeform_meta = {
        "current_version": version,
        "prefix": prefix,
        "session_id": outcome.session_id,
        "turn_ids": outcome.turn_ids,
        "review_rounds": outcome.rounds,
        "build_number": chosen.number,
        "layout_errors": chosen.layout_errors,
        "grounding_issues": chosen.grounding,
        "warnings": outcome.warnings[:12],
        "static_warnings": [i.message for i in chosen.build.warnings[:12]],
        "ai_images": chosen.build.manifest.get("ai_images", []),
        "usage": dict(run.usage),
        "events": run.events[-40:],
        "qa_screenshots": f"gs://{run.bucket}/{prefix}_qa/" if qa_files else "",
        "renderer": bool(renderer_url()),
        "elapsed_seconds": round(run.elapsed(), 1),
        "run_id": run.run_id,
        "model": designer_model(),
        "engine": engine_name(),
    }
    return {
        "render_mode": "freeform",
        "design_mode": "freeform",
        "freeform_prefix": prefix,
        "freeform": freeform_meta,
        "freeform_versions": versions[-MAX_VERSIONS:],
        "slide_count": chosen.build.slide_count,
        "slide_titles": titles,
        "gcs_bucket": run.bucket,
        "gcs_blob_path": prefix + "index.html",
        "gcs_uri": f"gs://{run.bucket}/{prefix}index.html",
        "content_version": int(data.get("content_version") or 0) + 1,
        "updated_at": now,
    }


def seed_from_published(store: Store, data: dict[str, Any]) -> tuple[dict[str, bytes], dict[str, bytes]]:
    """Returns (published_files, editable_seed). The seed restores the agent's raw HTML as index.html."""
    prefix = str(data.get("freeform_prefix") or (data.get("freeform") or {}).get("prefix") or "")
    if not prefix:
        return {}, {}
    published = store.read_all(prefix)
    seed: dict[str, bytes] = {}
    for path, blob in published.items():
        if path.startswith("_qa/") or path == "index.html":
            continue
        if path == "source.html":
            seed["index.html"] = blob
        else:
            seed[path] = blob
    if "index.html" not in seed and "index.html" in published:
        seed["index.html"] = published["index.html"]
    return published, seed


def new_run(presentation_id: str, project_id: str, bucket: str, status_cb: StatusCallback) -> Run:
    run_id = datetime.datetime.now(datetime.timezone.utc).strftime("%Y%m%dT%H%M%SZ") + "-" + uuid.uuid4().hex[:6]
    return Run(presentation_id=presentation_id, run_id=run_id, bucket=bucket, project_id=project_id, budget=Budget.from_env(), status_cb=status_cb)
