@dataclasses.dataclass
class BuildRecord:
    number: int
    build: dc.BuildResult
    prefix: str
    render: dict[str, Any] | None = None
    grounding: list[str] = dataclasses.field(default_factory=list)

    @property
    def publishable(self) -> bool:
        return not self.build.errors and "index.html" in self.build.files

    @property
    def layout_errors(self) -> int | None:
        return layout_error_count(self.render)


@dataclasses.dataclass
class Outcome:
    ok: bool
    chosen: BuildRecord | None
    builds: list[BuildRecord]
    session_id: str
    turn_ids: list[str]
    rounds: list[dict[str, Any]]
    draft_summary: str
    review_summaries: list[str]
    warnings: list[str]
    error: str = ""


def _record_build(
    run: Run, store: Store, files: dict[str, bytes], number: int, title: str, sources: str = ""
) -> BuildRecord:
    build = dc.build_publishable(files, title)
    prefix = f"{run.staging}build/r{number}/"
    grounding: list[str] = []
    if "index.html" in build.files:
        store.write_many(prefix, build.files)
        grounding = ungrounded_content(build.files["index.html"], sources)
    run.note(
        "build",
        number=number,
        errors=len(build.errors),
        warnings=len(build.warnings),
        slides=build.slide_count,
        grounding=grounding,
    )
    return BuildRecord(number=number, build=build, prefix=prefix, grounding=grounding)


def choose_build(builds: list[BuildRecord]) -> BuildRecord | None:
    """Final gate: publishable builds only; the latest unrendered build wins if it followed a fix,
    otherwise the rendered build with the fewest layout errors (latest on ties)."""
    candidates = [b for b in builds if b.publishable]
    if not candidates:
        return None
    latest = candidates[-1]
    rendered = [b for b in candidates if b.layout_errors is not None]
    if latest.layout_errors is None and latest is builds[-1]:
        return latest
    if not rendered:
        return latest
    return min(rendered, key=lambda b: (b.layout_errors, -b.number))


def _restore_ai_images(store: Store, prefix: str, files: dict[str, bytes], ai_files: dict[str, bytes]) -> None:
    """Re-adds images we generated if the designer deleted them (the designer cannot write raster files)."""
    missing = {p: b for p, b in ai_files.items() if p not in files}
    if missing:
        store.write_many(prefix, missing)
        files.update(missing)


def run_pipeline(
    run: Run,
    store: Store,
    designer: Any,
    *,
    mode: str,
    input_files: dict[str, str],
    seed_files: dict[str, bytes] | None = None,
    title: str = "",
) -> Outcome:
    """Draft -> images -> build/render -> review rounds -> final gate. Never raises."""
    turn_ids: list[str] = []
    rounds: list[dict[str, Any]] = []
    review_summaries: list[str] = []
    warnings: list[str] = []
    builds: list[BuildRecord] = []
    generated_prompts: dict[str, str] = {}
    ai_files: dict[str, bytes] = {}
    session_id = ""
    draft_summary = ""
    try:
        run.status("freeform_staging", "素材を準備しています")
        input_files = dict(input_files)
        if seed_files and "index.html" in seed_files:
            input_files.setdefault(PREVIOUS_DECK_TEXT, previous_deck_text_md(seed_files["index.html"]))
        sources = grounding_sources(input_files)
        store.write_many(run.staging + "input/", {k: v.encode("utf-8") for k, v in input_files.items()})
        if seed_files:
            store.write_many(run.deck_prefix, seed_files)

        # 1) Draft turn (create) or edit turn (edit) in a new designer session on the staging prefix.
        run.status("freeform_drafting", "デザイナーエージェントがスライドを制作しています")
        prompt = EDIT_PROMPT if mode == "edit" else DRAFT_PROMPT
        draft_deadline = max(60.0, min(float(run.budget.draft), run.remaining() - run.budget.reserve - 60))
        first = designer.start(prompt, workspace_spec(run))
        turn_ids.append(str(first.id))
        run.note("draft_started", turn_id=str(first.id), deadline=int(draft_deadline))
        final, timed_out = designer.wait(run, first, draft_deadline, "freeform_drafting", "デザイナーエージェントが制作中")
        session_id = str(getattr(final, "session_id", "") or "")
        draft_status = str(getattr(final, "status", "") or "").lower()
        draft_summary = strip_status_lines(str(getattr(final, "output_text", "") or ""))
        run.note("draft_done", status=draft_status, timed_out=timed_out, session_id=session_id, usage=run.add_usage(final))
        if timed_out:
            warnings.append("下書きが時間内に終わらなかったため、その時点のファイルで続行しました")

        # The designer's tools write to GCS synchronously, so the files are complete when the turn ends.
        files = store.read_all(run.deck_prefix)
        if "index.html" not in files:
            return Outcome(False, None, builds, session_id, turn_ids, rounds, draft_summary, review_summaries, warnings, "index.html が作成されませんでした")

        images, image_warnings = generate_ai_images(run, store, files, generated_prompts, ai_files)
        files.update(images)
        warnings.extend(image_warnings)

        builds.append(_record_build(run, store, files, 1, title, sources))
        # A completed turn can always be continued; a cancelled or incomplete turn is continued and degrades safely.
        can_continue = bool(session_id) and draft_status in ("completed", "cancelled", "canceled", "incomplete")

        # 2) Review rounds: render -> show the screenshots to the SAME agent (same ADK session)
        for round_no in range(1, run.budget.rounds + 1):
            current = builds[-1]
            if run.remaining() < run.budget.reserve + 75:
                warnings.append(f"時間の都合で見た目の確認 {round_no} 回目を省略しました")
                break
            run.status("freeform_checking", f"描画して見た目を検査しています（{round_no}/{run.budget.rounds}）")
            if "index.html" in current.build.files and current.render is None:
                current.render = render_build(run, current.prefix)
            needs_fix = bool(current.build.errors) or bool(current.layout_errors) or bool(current.grounding)
            if current.render is None and not current.build.errors and not current.grounding:
                break  # nothing to show and nothing to fix
            focus: set[int] | None = None
            if round_no > 1 and len(builds) >= 2:
                # Later rounds let the agent SEE its own fix: attach the slides whose screenshot changed plus
                # the slides that are still flagged. Nothing visible changed and nothing flagged -> done.
                focus = focus_slides(builds[-2].render, current.render)
                if focus is not None and not focus:
                    if not needs_fix:
                        break  # the fix changed nothing visible and the checks are clean
                    focus = None  # flagged problems are deck-level (CSP, charts, grounding): show everything
            if not can_continue:
                warnings.append("デザイナーのセッションを続けられなかったため、見た目の確認を省略しました")
                break
            turn_deadline = max(45.0, min(float(run.budget.review_turn), run.remaining() - run.budget.reserve))
            run.status("freeform_reviewing", f"エージェントがスクリーンショットを見て修正しています（{round_no}/{run.budget.rounds}）")
            before = _digest(files)
            notes = list(image_warnings) if round_no == 1 else []
            if current.grounding:
                notes.append(grounding_note(current.grounding))
            try:
                review = designer.start(
                    compose_review_input(round_no, run.budget.rounds, current.build, current.render, notes, focus),
                    session_id,
                )
            except Exception as exc:  # noqa: BLE001 - e.g. the session is still busy; keep the verified build
                warnings.append(f"見た目の確認 {round_no} 回目を開始できませんでした（{type(exc).__name__}）")
                run.note("review_start_failed", round=round_no, error=f"{type(exc).__name__}: {str(exc)[:300]}")
                break
            turn_ids.append(str(review.id))
            final_review, review_timed_out = designer.wait(
                run, review, turn_deadline, "freeform_reviewing", f"見た目の確認・修正 {round_no}/{run.budget.rounds}"
            )
            text = str(getattr(final_review, "output_text", "") or "")
            status = parse_review_status(text)
            usage = run.add_usage(final_review)
            files = store.read_all(run.deck_prefix)
            _restore_ai_images(store, run.deck_prefix, files, ai_files)
            changed = _digest(files) != before
            summary = strip_status_lines(text)
            if summary:
                review_summaries.append(summary)
            round_info = {
                "round": round_no,
                "turn_id": str(review.id),
                "status": str(getattr(final_review, "status", "")),
                "review_status": status or ("FIXED" if changed else "APPROVED"),
                "files_changed": changed,
                "timed_out": review_timed_out,
                "screenshots_sent": len(focus) if focus is not None else len((current.render or {}).get("slides", [])),
                "static_errors_before": len(current.build.errors),
                "layout_errors_before": current.layout_errors,
                "grounding_issues_before": len(current.grounding),
                "image_tokens": usage.get("image_input_tokens", 0),
                "total_tokens": usage.get("total_tokens", 0),
                "elapsed_seconds": round(run.elapsed(), 1),
            }
            rounds.append(round_info)
            run.note("review_done", **round_info)
            if not changed:
                if review_timed_out:
                    warnings.append(f"見た目の確認 {round_no} 回目が時間内に終わりませんでした")
                break
            more, more_warnings = generate_ai_images(run, store, files, generated_prompts, ai_files)
            files.update(more)
            warnings.extend(more_warnings)
            builds.append(_record_build(run, store, files, len(builds) + 1, title, sources))
            if review_timed_out:
                warnings.append(f"見た目の確認 {round_no} 回目が時間内に終わらず、途中までの修正を使いました")
                break

        # 3) Final render of the last build (QA screenshots + gate input) when time allows
        last = builds[-1]
        if last.publishable and last.render is None and run.remaining() > 45:
            run.status("freeform_checking", "最終版を描画して検査しています")
            last.render = render_build(run, last.prefix)
        chosen = choose_build(builds)
        if chosen is None:
            first_errors = "; ".join(i.message for i in builds[-1].build.errors[:3])
            return Outcome(False, None, builds, session_id, turn_ids, rounds, draft_summary, review_summaries, warnings, f"公開できる版がありません: {first_errors}")
        if chosen.layout_errors:
            warnings.append(f"レイアウト検査の指摘が {chosen.layout_errors} 件残っています")
        if chosen.grounding:
            warnings.append("入力資料で根拠を確認できない記載が残っています: " + "、".join(chosen.grounding[:5]))
        if chosen is not builds[-1]:
            warnings.append(f"最終修正版より検査結果が良かった r{chosen.number} を公開しました")
        return Outcome(True, chosen, builds, session_id, turn_ids, rounds, draft_summary, review_summaries, warnings)
    except Exception as exc:  # noqa: BLE001 - the worker decides on the fallback
        logger.exception("free-form pipeline failed for %s", run.presentation_id)
        chosen = choose_build(builds)
        if chosen is not None:
            warnings.append(f"途中でエラーが発生したため、検証済みの r{chosen.number} を公開します（{type(exc).__name__}）")
            return Outcome(True, chosen, builds, session_id, turn_ids, rounds, draft_summary, review_summaries, warnings)
        return Outcome(False, None, builds, session_id, turn_ids, rounds, draft_summary, review_summaries, warnings, f"{type(exc).__name__}: {str(exc)[:300]}")


