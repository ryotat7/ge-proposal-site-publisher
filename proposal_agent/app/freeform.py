def placeholder_png(width: int = 320, height: int = 180, rgb: tuple[int, int, int] = (226, 232, 240)) -> bytes:
    raw = (b"\x00" + bytes(rgb) * width) * height

    def chunk(tag: bytes, data: bytes) -> bytes:
        return struct.pack(">I", len(data)) + tag + data + struct.pack(">I", zlib.crc32(tag + data) & 0xFFFFFFFF)

    return (
        b"\x89PNG\r\n\x1a\n"
        + chunk(b"IHDR", struct.pack(">IIBBBBB", width, height, 8, 2, 0, 0, 0))
        + chunk(b"IDAT", zlib.compress(raw, 9))
        + chunk(b"IEND", b"")
    )


def parse_image_requests(files: dict[str, bytes]) -> tuple[list[dict[str, Any]], list[str]]:
    raw = files.get("image_requests.json")
    if raw is None:
        return [], []
    warnings: list[str] = []
    try:
        data = json.loads(raw.decode("utf-8"))
    except (UnicodeDecodeError, json.JSONDecodeError) as exc:
        return [], [f"image_requests.json を読めませんでした: {exc}"]
    if isinstance(data, dict):
        data = data.get("images") or data.get("requests") or []
    if not isinstance(data, list):
        return [], ["image_requests.json は配列にしてください"]
    requests: list[dict[str, Any]] = []
    for item in data:
        if not isinstance(item, dict):
            continue
        path = str(item.get("path") or "").strip()
        prompt = str(item.get("prompt") or "").strip()
        aspect = str(item.get("aspect_ratio") or "16:9").strip()
        if not AI_IMAGE_PATH_RE.match(path) or not prompt:
            warnings.append(f"AI 画像の依頼を無視しました（path か prompt が不正）: {path[:60]}")
            continue
        if len(requests) >= MAX_AI_IMAGES:
            warnings.append(f"AI 画像は最大 {MAX_AI_IMAGES} 枚です。{path} は生成しませんでした")
            continue
        requests.append(
            {
                "path": path,
                "prompt": prompt[:800],
                "aspect_ratio": aspect if aspect in AI_ASPECTS else "16:9",
            }
        )
    return requests, warnings


def _generate_image(project_id: str, prompt: str, aspect_ratio: str) -> bytes:
    from google import genai
    from google.genai import types

    client = genai.Client(
        vertexai=True, project=project_id, location="global", http_options=types.HttpOptions(timeout=80_000)
    )
    full_prompt = (
        prompt.strip()
        + "\nStrictly no text, letters, numbers, logos, watermarks or UI elements anywhere in the image."
    )
    config = types.GenerateContentConfig(
        response_modalities=["IMAGE"], image_config=types.ImageConfig(aspect_ratio=aspect_ratio)
    )
    resp = client.models.generate_content(model=image_model(), contents=full_prompt, config=config)
    for cand in resp.candidates or []:
        parts = cand.content.parts if cand.content and cand.content.parts else []
        for part in parts:
            if part.inline_data is not None and part.inline_data.data:
                return bytes(part.inline_data.data)
    raise RuntimeError("image model returned no image")


def generate_ai_images(
    run: Run,
    store: Store,
    files: dict[str, bytes],
    generated: dict[str, str],
    ai_files: dict[str, bytes],
) -> tuple[dict[str, bytes], list[str]]:
    """Generates requested images that are missing or whose prompt changed since we generated them.

    `generated` (path -> prompt) and `ai_files` (path -> bytes) are updated in place so later rounds can
    detect prompt changes and restore images that the designer deleted or overwrote.
    """
    requests, warnings = parse_image_requests(files)
    todo = [
        r
        for r in requests
        if (r["path"] not in files and r["path"] not in ai_files)
        or (r["path"] in generated and generated[r["path"]] != r["prompt"])
    ]
    if not todo:
        return {}, warnings
    run.status("freeform_images", f"AI 画像を {len(todo)} 枚生成しています")
    produced: dict[str, bytes] = {}
    timeout = max(20.0, min(100.0, run.remaining() - run.budget.reserve - 120))
    pool = concurrent.futures.ThreadPoolExecutor(max_workers=min(4, len(todo)))
    futures = {pool.submit(_generate_image, run.project_id, r["prompt"], r["aspect_ratio"]): r for r in todo}
    try:
        for fut in concurrent.futures.as_completed(futures, timeout=timeout):
            req = futures[fut]
            try:
                data = fut.result()
                if dc.sniff_raster(data) is None:
                    raise RuntimeError("not a raster image")
                produced[req["path"]] = data
            except Exception as exc:  # noqa: BLE001
                warnings.append(f"AI 画像 {req['path']} を生成できず仮の画像を置きました（{type(exc).__name__}）")
                produced[req["path"]] = placeholder_png()
    except concurrent.futures.TimeoutError:
        for fut, req in futures.items():
            if req["path"] not in produced:
                fut.cancel()
                warnings.append(f"AI 画像 {req['path']} は時間内に生成できず仮の画像を置きました")
                produced[req["path"]] = placeholder_png()
    finally:
        pool.shutdown(wait=False, cancel_futures=True)
    for req in todo:
        generated[req["path"]] = req["prompt"]
    ai_files.update(produced)
    store.write_many(run.deck_prefix, produced)
    run.note("ai_images", generated=sorted(produced), warnings=warnings[-4:])
    return produced, warnings


