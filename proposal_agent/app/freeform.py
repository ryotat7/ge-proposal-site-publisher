class Store:
    """Thin GCS wrapper (swappable in tests)."""

    def __init__(self, project_id: str, bucket: str) -> None:
        from google.cloud import storage

        self.client = storage.Client(project=project_id)
        self.bucket_name = bucket
        self.bucket = self.client.bucket(bucket)

    def list_meta(self, prefix: str) -> dict[str, tuple[int, int]]:
        return {
            b.name[len(prefix) :]: (int(b.size or 0), int(b.generation or 0))
            for b in self.client.list_blobs(self.bucket_name, prefix=prefix)
            if not b.name.endswith("/")
        }

    def read_all(self, prefix: str, max_files: int = 250, max_bytes: int = 40_000_000) -> dict[str, bytes]:
        blobs = [b for b in self.client.list_blobs(self.bucket_name, prefix=prefix) if not b.name.endswith("/")]
        out: dict[str, bytes] = {}
        total = 0
        for blob in blobs[:max_files]:
            total += int(blob.size or 0)
            if total > max_bytes:
                break
            out[blob.name[len(prefix) :]] = blob.download_as_bytes()
        return out

    def read(self, path: str) -> bytes | None:
        blob = self.bucket.blob(path)
        try:
            return blob.download_as_bytes()
        except Exception:  # noqa: BLE001 - missing object
            return None

    def write(self, path: str, data: bytes, content_type: str | None = None) -> None:
        blob = self.bucket.blob(path)
        blob.cache_control = "no-store, private"
        blob.upload_from_string(data, content_type=content_type or dc.content_type_for_bytes(path, data))

    def delete(self, path: str) -> None:
        try:
            self.bucket.blob(path).delete()
        except Exception:  # noqa: BLE001 - already gone
            pass

    def write_many(self, prefix: str, files: dict[str, bytes]) -> None:
        with concurrent.futures.ThreadPoolExecutor(max_workers=8) as pool:
            list(pool.map(lambda kv: self.write(prefix + kv[0], kv[1], dc.content_type_for_bytes(kv[0], kv[1])), files.items()))



