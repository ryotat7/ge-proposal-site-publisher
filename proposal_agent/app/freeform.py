def renderer_url() -> str:
    return os.environ.get("DECK_RENDERER_URL", "").strip().rstrip("/")


def render_build(run: Run, prefix: str) -> dict[str, Any] | None:
    url = renderer_url()
    if not url:
        return None
    budget = max(25.0, min(200.0, run.remaining() - 15))
    try:
        import httpx

        headers: dict[str, str] = {}
        if not url.startswith(("http://127.0.0.1", "http://localhost")):
            import google.auth.transport.requests
            import google.oauth2.id_token

            token = google.oauth2.id_token.fetch_id_token(google.auth.transport.requests.Request(), url)
            headers["Authorization"] = f"Bearer {token}"
        resp = httpx.post(
            f"{url}/v1/render",
            json={
                "bucket": run.bucket,
                "prefix": prefix,
                "width": run.budget.image_width,
                "format": "jpeg",
                "quality": 78,
                "timeout_seconds": int(max(15, min(180, budget - 10))),
            },
            headers=headers,
            timeout=budget,
        )
        resp.raise_for_status()
        result = resp.json()
        run.note(
            "render",
            prefix=prefix,
            ok=result.get("ok"),
            slides=len(result.get("slides", [])),
            layout_errors=layout_error_count(result),
            elapsed_ms=result.get("elapsed_ms"),
            error=result.get("error", ""),
        )
        return result
    except Exception as exc:  # noqa: BLE001 - the review loop degrades to static checks
        run.note("render_failed", prefix=prefix, error=f"{type(exc).__name__}: {str(exc)[:200]}")
        return None


