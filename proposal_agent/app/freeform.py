"""Free-form presentations designed by an ADK agent, with a visual review loop.

Create and edit runs share one pipeline (all state lives in GCS + Firestore, so the job is restartable):

  stage inputs -> draft turn (ADK LlmAgent whose file tools read and write gs://<bucket>/staging/<id>/<run>/,
     shown to the model as /workspace/job)
    -> AI images (gemini-3.1-flash-image, generated by the worker)
    -> build r1 (deck_contract: sanitise + validate) + grounding check -> render (private Chromium service)
    -> review turn k: SAME ADK session, screenshots sent as image parts of the user turn
       -> agent edits files -> build r(k+1) -> render ...
    -> final gate (no static errors, fewest layout errors) -> publish presentations/<id>/v<N>/

The designer itself lives in app/adk_designer.py (`start()` / `wait()`); everything else is in this module.
"""

