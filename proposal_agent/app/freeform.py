def _issue_lines(build: dc.BuildResult, limit: int = 12) -> list[str]:
    lines = [f"- [エラー] {i.file or '-'}: {i.message}" for i in build.errors[:limit]]
    lines += [f"- [警告] {i.file or '-'}: {i.message}" for i in build.warnings[: max(0, limit - len(lines))]]
    return lines


def _render_problem_lines(render: dict[str, Any]) -> list[str]:
    lines: list[str] = []
    for item in render.get("console_errors", [])[:6]:
        lines.append(f"- [コンソール] {item.get('text', '')[:160]}")
    for item in render.get("failed_requests", [])[:6]:
        lines.append(f"- [読み込み失敗] {item.get('url', '')[:120]} {item.get('error', '')}")
    for item in render.get("csp_violations", [])[:6]:
        lines.append(f"- [CSP でブロック] {item.get('directive', '')} {item.get('blocked', '')[:100]}")
    for item in render.get("chart_errors", [])[:6]:
        lines.append(f"- [グラフ] {item.get('chart', '')}: {item.get('detail', '')[:160]}")
    for item in render.get("runtime_errors", [])[:6]:
        lines.append(f"- [ランタイム] {item.get('type', '')}: {item.get('detail', '')[:160]}")
    return lines


def layout_error_count(render: dict[str, Any] | None) -> int | None:
    if not render or not render.get("ok"):
        return None
    count = sum(1 for s in render.get("slides", []) for i in s.get("issues", []) if i.get("severity") == "error")
    return count + len(render.get("csp_violations", [])) + len(render.get("chart_errors", [])) + len(render.get("runtime_errors", []))


def compose_review_input(
    round_no: int,
    rounds: int,
    build: dc.BuildResult,
    render: dict[str, Any] | None,
    extra_notes: list[str],
    only_slides: set[int] | None = None,
) -> list[dict[str, Any]]:
    """User turn for a review round: summary text + one labelled screenshot per slide (image parts).

    `only_slides` (0-based indexes) limits which screenshots are attached in later rounds; the other slides
    are listed as text only. Each attached image costs roughly 1.1k input tokens per internal model step.
    """
    header = [f"【見た目の確認 {round_no}/{rounds} 回目】"]
    if render and render.get("slides"):
        header.append(
            "あなたの deck を公開用に無害化して、ヘッドレス Chrome（1920×1080）で描画しました。"
            "このあと各スライドのスクリーンショットを順番に添付します。画像を実際に見て確認してください。"
        )
        if only_slides is not None:
            header.append("前回から見た目が変わったスライドと、指摘が残っているスライドだけ画像を添付します。")
    else:
        header.append("描画サービスを利用できなかったため、静的検査の結果だけをお送りします。")
    static = _issue_lines(build)
    header.append("\n■ 静的検査（公開前の契約チェック）")
    header.extend(static or ["- 指摘なし"])
    if render:
        problems = _render_problem_lines(render)
        header.append("\n■ 描画時の問題（コンソール・読み込み・CSP・グラフ）")
        header.extend(problems or ["- 指摘なし"])
    if extra_notes:
        header.append("\n■ ワーカーからの補足")
        header.extend(f"- {n}" for n in extra_notes[:8])
    content: list[dict[str, Any]] = [{"type": "text", "text": "\n".join(header)}]
    for slide in (render or {}).get("slides", []):
        index = int(slide.get("index", 0))
        issues = slide.get("issues", [])
        detail = "; ".join(f"{i.get('type')}: {i.get('detail', '')} {i.get('element', '')}".strip() for i in issues[:6])
        attach = bool(slide.get("screenshot_b64")) and (only_slides is None or index in only_slides)
        suffix = "" if attach or only_slides is None else "（前回から変化なし・画像省略）"
        content.append(
            {"type": "text", "text": f"スライド {index + 1}「{slide.get('title', '')}」 自動検査: {detail or '指摘なし'}{suffix}"}
        )
        if attach:
            content.append({"type": "image", "data": slide["screenshot_b64"], "mime_type": "image/jpeg"})
    content.append(
        {
            "type": "text",
            "text": (
                "確認の観点（1 枚ずつ、細部まで見てください）:\n"
                "1. 文字のはみ出し・重なり・切れ。図（SVG）の中で、矢印や線がラベルを横切っていないか、ラベルが箱に隠れたり途中で切れたりしていないか\n"
                "2. 要素の欠け（画像・グラフ・図）\n"
                "3. 文字サイズ（本文 24px 以上・脚注 18px 以上）とコントラスト\n"
                "4. 本文とビジュアルの食い違い（本文で書いた色・凡例・数値・順序が、グラフや図と一致しているか）\n"
                "5. グラフの軸・単位・数値（brief.md と knowledge.md にない数値は「試算」「イメージ」と表示し、「実績」とは書かない）\n"
                "6. 余白・整列・視線の流れ、スライド間のデザインの一貫性\n"
                "7. 1 枚 1 メッセージになっているか、タイトルが要点を言い切っているか\n\n"
                f"問題があれば {MOUNT_TARGET}/deck/ のファイルを直接修正してください（新しいスクリーンショットは撮れません。修正後はこちらで再描画します）。"
                "問題がなければ何も変更しないでください。\n"
                "返答は日本語で 3〜6 行の修正要約と、最終行に `REVIEW_STATUS: FIXED`（修正した）または `REVIEW_STATUS: APPROVED`（修正不要）。"
            ),
        }
    )
    return [{"type": "user_input", "content": content}]


def focus_slides(previous: dict[str, Any] | None, current: dict[str, Any] | None) -> set[int] | None:
    """Slides whose screenshot changed since the previous render or that still have error-level issues.

    Returns None (= attach every slide) when the renders are not comparable.
    """
    if not previous or not current or not previous.get("slides") or not current.get("slides"):
        return None
    prev = {int(s.get("index", 0)): hashlib.sha256(str(s.get("screenshot_b64", "")).encode()).hexdigest() for s in previous["slides"]}
    if len(prev) != len(current["slides"]):
        return None
    focus: set[int] = set()
    for slide in current["slides"]:
        index = int(slide.get("index", 0))
        digest = hashlib.sha256(str(slide.get("screenshot_b64", "")).encode()).hexdigest()
        if prev.get(index) != digest or any(i.get("severity") == "error" for i in slide.get("issues", [])):
            focus.add(index)
    return focus


def parse_review_status(text: str) -> str:
    match = REVIEW_STATUS_RE.search(text or "")
    return match.group(1).upper() if match else ""


def strip_status_lines(text: str) -> str:
    cleaned = re.sub(r"(REVIEW_STATUS|DRAFT_STATUS):\s*\w+", "", text or "")
    return cleaned.strip()[:1500]


# ---------------------------------------------------------------------------
# Grounding check (numbers, email addresses and work-file names on the slides)
# ---------------------------------------------------------------------------
_INVISIBLE_RE = re.compile(r"<(script|style|template|noscript)\b.*?</\1\s*>|<!--.*?-->", re.S | re.I)
_PERCENT_RE = re.compile(r"(?<![\d.,])(\d{1,4}(?:\.\d+)?)\s*(?:%|パーセント)")
_EMAIL_RE = re.compile(r"[A-Za-z0-9._%+-]+@[A-Za-z0-9-]+(?:\.[A-Za-z0-9-]+)+")
_HEDGE_WORDS = ("試算", "イメージ", "想定", "目標", "見込")
# A hedge word only covers numbers in the same clause: element boundaries and these marks end a clause.
_CLAUSE_BREAKS = "\n。、・,;|/"


def visible_text(markup: str) -> str:
    """Text a viewer can read: tags, scripts, styles and comments removed, entities decoded."""
    text = _INVISIBLE_RE.sub(" ", markup or "")
    text = re.sub(r"<[^>]+>", " ", text)
    return re.sub(r"\s+", " ", html.unescape(text)).strip()


def previous_deck_text_md(index_html: bytes | str) -> str:
    raw = index_html.decode("utf-8", errors="replace") if isinstance(index_html, bytes) else str(index_html or "")
    return "# 公開中の版の本文（参考）\n\n" + visible_text(raw)[:30000] + "\n"


def grounding_sources(input_files: dict[str, str]) -> str:
    return "\n".join(str(input_files.get(name) or "") for name in GROUNDING_INPUTS)


def _norm_number(raw: str) -> str:
    value = raw.replace(",", "")
    if "." in value:
        value = value.rstrip("0").rstrip(".")
    return value or "0"


def _clause_around(text: str, start: int, end: int, reach: int = 30) -> str:
    left = text[max(0, start - reach) : start]
    right = text[end : end + reach]
    cut_left = max(left.rfind(mark) for mark in _CLAUSE_BREAKS)
    cuts_right = [i for i in (right.find(mark) for mark in _CLAUSE_BREAKS) if i >= 0]
    return left[cut_left + 1 :] + text[start:end] + right[: min(cuts_right) if cuts_right else len(right)]


def ungrounded_content(index_html: bytes | str, sources: str, limit: int = 10) -> list[str]:
    """Items on the slides that the inputs do not support: percentages that appear in no input and are not
    labelled as an estimate, email addresses, and work-file names or paths. Returns short labels."""
    raw = index_html.decode("utf-8", errors="replace") if isinstance(index_html, bytes) else str(index_html or "")
    lines = re.sub(r"<[^>]+>", "\n", _INVISIBLE_RE.sub(" ", raw))
    text = unicodedata.normalize("NFKC", html.unescape(lines))
    src = unicodedata.normalize("NFKC", sources or "")
    known = {_norm_number(m.group(1)) for m in _PERCENT_RE.finditer(src)}
    issues: list[str] = []
    seen: set[str] = set()
    for match in _PERCENT_RE.finditer(text):
        value = _norm_number(match.group(1))
        if value in known or value in ("0", "100") or value in seen:
            continue
        if any(word in _clause_around(text, match.start(), match.end()) for word in _HEDGE_WORDS):
            continue
        seen.add(value)
        issues.append(f"数値「{match.group(0).strip()}」")
    src_low = src.lower()
    for email in sorted({e.lower() for e in _EMAIL_RE.findall(text)}):
        if email not in src_low:
            issues.append(f"メールアドレス「{email}」")
    low = text.lower()
    for name in WORK_FILE_NAMES:
        if name.lower() in low:
            issues.append(f"作業用のファイル名・パス「{name}」")
    return issues[:limit]


def grounding_note(issues: list[str]) -> str:
    """Instruction for the designer about ungrounded items (empty when there are none)."""
    if not issues:
        return ""
    return (
        "入力資料で根拠を確認できない記載: "
        + "、".join(issues)
        + "。入力にない数値は削除するか「試算」「イメージ」と明記し、入力にないメールアドレスや作業用のファイル名・パスはスライドから消してください。"
    )


